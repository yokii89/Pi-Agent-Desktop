/**
 * Persist a view-sdk coverage snapshot so "before" and "after" numbers for
 * docs/design/20 are comparable with the same command (准则 §13.1).
 *
 * Reads `packages/view-sdk/coverage/coverage-summary.json` (written by
 * `pnpm test:sdk:coverage`) and copies a normalized table into
 * `docs/design/baseline/`.
 *
 * Usage:
 *   node scripts/sdk-coverage-snapshot.mjs                # stage defaults to "current"
 *   node scripts/sdk-coverage-snapshot.mjs --stage before
 *   node scripts/sdk-coverage-snapshot.mjs --stage after
 *
 * `pnpm test:sdk:coverage` chains this without `--stage`, so a plain coverage
 * run always leaves a `current` snapshot on disk (准则 §13.1 可复现口径).
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const summaryPath = join(root, "packages", "view-sdk", "coverage", "coverage-summary.json");
const outDir = join(root, "docs", "design", "baseline");

function stage() {
  const i = process.argv.indexOf("--stage");
  const value = i === -1 ? undefined : process.argv[i + 1];
  if (value === undefined) return "current";
  if (!value || value.startsWith("--")) {
    throw new Error("Usage: node scripts/sdk-coverage-snapshot.mjs [--stage <label>]");
  }
  return value;
}

function pct(metric) {
  return metric == null ? "—" : `${metric.pct}%`;
}

function main() {
  const label = stage();
  let summary;
  try {
    summary = JSON.parse(readFileSync(summaryPath, "utf8"));
  } catch {
    throw new Error(
      `Missing ${relative(root, summaryPath)} — run \`pnpm test:sdk:coverage\` first.`,
    );
  }

  const rows = [];
  for (const [file, metrics] of Object.entries(summary)) {
    const name = file.replace(/\\/g, "/").split("/src/").pop();
    if (!name) continue;
    rows.push({
      file: name,
      lines: pct(metrics.lines),
      branches: pct(metrics.branches),
      uncoveredBranches: metrics.branches.total - metrics.branches.covered,
    });
  }
  rows.sort((a, b) => a.file.localeCompare(b.file));

  const total = summary.total;
  const md = [
    `# view-sdk coverage — stage \`${label}\``,
    "",
    "> Generated by `scripts/sdk-coverage-snapshot.mjs`. Source of truth for docs/design/20 §4.",
    `> Captured ${new Date().toISOString()}`,
    "",
    `**Total: lines ${pct(total.lines)} · branches ${pct(total.branches)}**`,
    "",
    "| File | Lines | Branches | Uncovered branches |",
    "| --- | --- | --- | --- |",
    ...rows.map(
      (r) => `| \`src/${r.file}\` | ${r.lines} | ${r.branches} | ${r.uncoveredBranches} |`,
    ),
    "",
  ].join("\n");

  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, `view-sdk-coverage.${label}.md`), md, "utf8");
  writeFileSync(
    join(outDir, `view-sdk-coverage.${label}.json`),
    `${JSON.stringify(summary, null, 2)}\n`,
    "utf8",
  );
  console.log(
    `Total lines ${pct(total.lines)} / branches ${pct(total.branches)} → docs/design/baseline/view-sdk-coverage.${label}.md`,
  );
}

main();
