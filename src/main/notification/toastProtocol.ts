import type { SystemToastRequest } from "../../shared/notification";

/** Escape plain text before embedding it in Windows toast XML. */
export function escapeToastXml(value: string): string {
  return value.replace(/[&<>"']/g, (char) => {
    const entities: Record<string, string> = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&apos;",
    };
    return entities[char];
  });
}

/** Protocol activation bypasses Electron's COM relaunch of electron.exe without the app path. */
export function buildToastXml(title: string, body: string, launch: string, icon?: string): string {
  const image = icon ? `<image placement="appLogoOverride" src="${escapeToastXml(icon)}"/>` : "";
  return `<toast activationType="protocol" launch="${escapeToastXml(launch)}"><visual><binding template="ToastGeneric">${image}<text>${escapeToastXml(title)}</text><text>${escapeToastXml(body)}</text></binding></visual><audio silent="true"/></toast>`;
}

/** Only accept tokens generated by this process; protocol links cannot supply arbitrary file paths. */
export function parseToastToken(argv: string[], protocol: string): string | undefined {
  for (const arg of argv) {
    try {
      const url = new URL(arg);
      if (
        url.protocol === `${protocol}:` &&
        url.hostname === "notification" &&
        /^\/[a-f0-9-]{36}$/.test(url.pathname) &&
        !url.search &&
        !url.hash &&
        !url.username &&
        !url.password &&
        !url.port
      ) {
        return url.pathname.slice(1);
      }
    } catch {
      // Other Electron arguments are not URLs.
    }
  }
  return undefined;
}

/** Bound notification targets independently of native toast dismissal events. */
export class ToastTargets {
  private readonly targets = new Map<
    string,
    Pick<SystemToastRequest, "sessionId" | "sessionFile">
  >();

  add(token: string, request: SystemToastRequest): void {
    this.targets.set(token, { sessionId: request.sessionId, sessionFile: request.sessionFile });
    if (this.targets.size > 128) {
      const oldest = this.targets.keys().next().value;
      if (oldest !== undefined) this.targets.delete(oldest);
    }
  }

  take(token: string): Pick<SystemToastRequest, "sessionId" | "sessionFile"> | undefined {
    const target = this.targets.get(token);
    this.targets.delete(token);
    return target;
  }
}
